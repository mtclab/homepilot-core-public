"""The schema the migration chain produces, written down, and the lock that holds it.

`schema.lock` (beside this file) is generated by this module and committed. It
records two things:

* **history** - one content hash per migration version. A released version is
  applied history: installs that already ran it never run it again, so editing
  it splits fresh installs from upgraded ones without either noticing.
* **schema** - the final schema as text: every table's columns (type, NOT
  NULL, default, key), foreign keys, indexes (columns, unique, partial) and the
  normalised `CREATE` statement of every table, index, view and trigger. Its
  sha256 is the fingerprint.

`tests/test_schema_fingerprint.py` rebuilds the schema from a fresh migrate and
from an upgrade off every older version and fails on any difference, so a
schema change nobody recorded cannot ship. After an INTENDED change:

    make schema-lock

which runs `python -m homepilot.db.schema_fingerprint --write`. It refuses to
change the hash of a version the lock already holds unless `--rewrite-history`
says that version was never released.
"""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import re
import sys
import tempfile
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import TYPE_CHECKING

from .connection import Database

if TYPE_CHECKING:
    from .migrations import Statement

LOCK_PATH = Path(__file__).with_name("schema.lock")
UPDATE_COMMAND = "make schema-lock"

_HEADER = (
    "# Generated by homepilot.db.schema_fingerprint - do not edit by hand.\n"
    f"# After an intended schema change, regenerate it:  {UPDATE_COMMAND}\n"
    "# tests/test_schema_fingerprint.py fails when the migration chain differs from it.\n"
)


def _norm_sql(sql: str | None) -> str:
    return re.sub(r"\s+", " ", sql or "").strip()


def statement_digest(statements: Sequence[Statement]) -> str:
    """Content hash of one version's statements, exactly as the runner sees them."""
    payload = json.dumps([list(e) if isinstance(e, tuple) else e for e in statements])
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def history_digests(migrations: Mapping[int, Sequence[Statement]]) -> dict[int, str]:
    return {v: statement_digest(migrations[v]) for v in sorted(migrations)}


async def describe_schema(db: Database) -> list[str]:
    """The schema of `db` as sorted, line-oriented text. Data is not included.

    Shadow tables of virtual tables (sqlite-vec's `vec_docs_*`) are left out:
    their layout belongs to the extension's version, not to our migrations. The
    virtual table's own `CREATE` is kept.
    """
    lines: list[str] = []
    tables = await db.fetchall(
        "SELECT name, type FROM pragma_table_list WHERE schema = 'main' "
        "AND name NOT LIKE 'sqlite_%' AND type IN ('table', 'virtual', 'view') ORDER BY name"
    )
    # sqlite-vec declares only some of its shadow tables as such (its
    # `<name>_vector_chunksNN` report as plain tables), so go by the prefix the
    # extension gives every one of them as well.
    virtual = [t["name"] for t in tables if t["type"] == "virtual"]
    for t in tables:
        name, kind = t["name"], t["type"]
        if kind == "table" and any(name.startswith(v + "_") for v in virtual):
            continue
        row = await db.fetchone("SELECT sql FROM sqlite_master WHERE name = ?", (name,))
        lines.append(f"{kind} {name}")
        lines.append(f"  sql {_norm_sql(row['sql'] if row else None)}")
        if kind != "table":
            continue
        for c in await db.fetchall("SELECT * FROM pragma_table_xinfo(?) ORDER BY cid", (name,)):
            lines.append(
                f"  column {c['name']} type={c['type'] or '-'} notnull={c['notnull']} "
                f"default={c['dflt_value']} pk={c['pk']} hidden={c['hidden']}"
            )
        for fk in await db.fetchall(
            "SELECT * FROM pragma_foreign_key_list(?) ORDER BY id, seq", (name,)
        ):
            lines.append(
                f"  fk {fk['from']} -> {fk['table']}({fk['to']}) "
                f"on_update={fk['on_update']} on_delete={fk['on_delete']}"
            )
        for ix in await db.fetchall("SELECT * FROM pragma_index_list(?) ORDER BY name", (name,)):
            cols = await db.fetchall(
                "SELECT name, desc, coll FROM pragma_index_xinfo(?) WHERE key = 1 ORDER BY seqno",
                (ix["name"],),
            )
            col_text = ",".join(
                f"{c['name'] or '<expr>'}{' DESC' if c['desc'] else ''}"
                f"{'' if c['coll'] == 'BINARY' else ' COLLATE ' + str(c['coll'])}"
                for c in cols
            )
            sql_row = await db.fetchone(
                "SELECT sql FROM sqlite_master WHERE type = 'index' AND name = ?", (ix["name"],)
            )
            lines.append(
                f"  index {ix['name']} unique={ix['unique']} origin={ix['origin']} "
                f"partial={ix['partial']} cols=({col_text}) "
                f"sql={_norm_sql(sql_row['sql'] if sql_row else None) or '-'}"
            )
    for trg in await db.fetchall(
        "SELECT name, tbl_name, sql FROM sqlite_master WHERE type = 'trigger' ORDER BY name"
    ):
        lines.append(f"trigger {trg['name']} on {trg['tbl_name']}")
        lines.append(f"  sql {_norm_sql(trg['sql'])}")
    return lines


def schema_sha256(schema_lines: Sequence[str]) -> str:
    return hashlib.sha256("\n".join(schema_lines).encode("utf-8")).hexdigest()


def render_lock(schema_lines: Sequence[str], history: Mapping[int, str]) -> str:
    out = [
        _HEADER.rstrip("\n"),
        f"schema_version {max(history)}",
        f"schema_sha256 {schema_sha256(schema_lines)}",
        "",
        "[history]",
        *(f"{v} {digest}" for v, digest in sorted(history.items())),
        "",
        "[schema]",
        *schema_lines,
    ]
    return "\n".join(out) + "\n"


def parse_lock(text: str) -> tuple[dict[int, str], list[str], str]:
    """`(history, schema_lines, recorded_sha256)` from a lock file's text."""
    history: dict[int, str] = {}
    schema: list[str] = []
    recorded = ""
    section = ""
    for line in text.splitlines():
        if line.startswith("#"):
            continue
        if line in ("[history]", "[schema]"):
            section = line
            continue
        if not section:
            if line.startswith("schema_sha256 "):
                recorded = line.split(" ", 1)[1]
            continue
        if section == "[history]":
            if line:
                version, digest = line.split(" ", 1)
                history[int(version)] = digest
        else:
            schema.append(line)
    return history, schema, recorded


async def migrate_and_describe(db_path: str, upto: int | None = None) -> list[str]:
    """Run the chain (optionally only to `upto`, then the rest) and describe the result."""
    from . import migrations as mig

    database = Database(db_path)
    await database.connect()
    try:
        if upto:  # version 0 is an empty database: nothing to run first
            full = dict(mig.MIGRATIONS)
            try:
                for version in [v for v in full if v > upto]:
                    del mig.MIGRATIONS[version]
                await mig.run_migrations(database)
            finally:
                mig.MIGRATIONS.clear()
                mig.MIGRATIONS.update(full)
        await mig.run_migrations(database)
        return await describe_schema(database)
    finally:
        await database.close()


def main(argv: Sequence[str] | None = None) -> int:
    from .migrations import MIGRATIONS

    parser = argparse.ArgumentParser(prog="python -m homepilot.db.schema_fingerprint")
    parser.add_argument("--write", action="store_true", help=f"rewrite {LOCK_PATH.name}")
    parser.add_argument(
        "--rewrite-history",
        action="store_true",
        help="allow a recorded version's hash to change (ONLY for a never-released version)",
    )
    args = parser.parse_args(argv)

    with tempfile.TemporaryDirectory(prefix="hp-schema-lock-") as tmp:
        schema = asyncio.run(migrate_and_describe(str(Path(tmp) / "homepilot.db")))
    history = history_digests(MIGRATIONS)
    rendered = render_lock(schema, history)
    current = LOCK_PATH.read_text(encoding="utf-8") if LOCK_PATH.exists() else ""

    if not args.write:
        if rendered == current:
            print(f"{LOCK_PATH.name}: up to date (schema_sha256 {schema_sha256(schema)})")
            return 0
        print(f"{LOCK_PATH.name} is out of date; run: {UPDATE_COMMAND}", file=sys.stderr)
        return 1

    old_history, _schema, _sha = parse_lock(current)
    changed = sorted(v for v, d in old_history.items() if history.get(v) != d)
    if changed and not args.rewrite_history:
        print(
            f"refusing to rewrite {LOCK_PATH.name}: the content of recorded schema "
            f"version(s) {changed} changed. A released migration is applied history - "
            "add a NEW version instead. If those versions were never released, rerun "
            "with --rewrite-history.",
            file=sys.stderr,
        )
        return 2
    LOCK_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {LOCK_PATH} (schema_version {max(history)}, sha256 {schema_sha256(schema)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
